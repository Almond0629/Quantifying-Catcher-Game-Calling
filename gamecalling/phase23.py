"""Phases 2-3 pilot report (revision after review): ranking, bootstrap diagnostics, recovery, coverage.

Run with: python3.12 -m gamecalling.phase23
Inputs: data/phase1_scores.parquet; simulation v2 (gamecalling.simulation); coverage v1
(gamecalling.coverage_sim); optional bootstrap replicates per method (gamecalling.bootstrap);
reports/bootstrap_trace.md and reports/network_pilot.md (their own modules).
Writes reports/phase23_pilot.md, reports/leaderboard_pilot.csv, reports/simulation_summary.csv,
reports/coverage_summary.csv. No 2024-2025 persistence correlation is computed.
"""

import numpy as np
import pandas as pd

from gamecalling import bootstrap, config, coverage_sim, ranking, simulation
from gamecalling.phase1 import SCORES_PARQUET, _md

REPORT = config.REPORTS_DIR / "phase23_pilot.md"
QUALIFY = 1000


def point_estimates(scores: pd.DataFrame):
    fits = ranking.fit_scores(scores, bootstrap.SCORES, bootstrap.MODELS)
    return fits, bootstrap.effects_table(fits)


def leaderboard(scores, point, boot_iv: dict) -> pd.DataFrame:
    """Point estimates (runs saved per 100 pitches) with any available bootstrap intervals, labeled by method."""
    rows = []
    for season, g in scores.groupby("season"):
        shared = ranking.shared_pitchers(g)
        p = point[(point["season"] == season)]
        d = p[(p["score"] == "D") & (p["model"] == "random")].set_index("catcher")
        q = d.index[d["n_pitches"] >= QUALIFY]
        out = pd.DataFrame({"season": season, "catcher": q, "pitches": d.loc[q, "n_pitches"].to_numpy(),
                            "shared_pitchers": shared.reindex(q).fillna(0).astype(int).to_numpy()})
        for score in ("D", "A"):
            for model in ("random", "fixed"):
                e = p[(p["score"] == score) & (p["model"] == model)].set_index("catcher")["effect"]
                out[f"{score}_{model}_saved"] = -e.reindex(q).to_numpy()
        for method, iv in boot_iv.items():
            r = iv[(iv["season"] == season) & (iv["model"] == "random")]
            for score in ("D", "A"):
                s = r[r["score"] == score].set_index("catcher")
                out[f"{score}_{method}_lo"] = -s["hi"].reindex(q).to_numpy()
                out[f"{score}_{method}_hi"] = -s["lo"].reindex(q).to_numpy()
        rows.append(out.sort_values("D_random_saved", ascending=False))
    return pd.concat(rows, ignore_index=True)


def variance_table(fits) -> pd.DataFrame:
    rows = []
    for (season, score, model), f in sorted(fits.items()):
        rows.append(dict(season=season, score=score, model=model, sd_catcher=np.sqrt(f.variances["catcher"]),
                         sd_pitcher=np.sqrt(f.variances.get("pitcher", np.nan)), sd_resid=np.sqrt(f.sigma2),
                         converged=f.converged))
    return pd.DataFrame(rows)


def main() -> None:
    scores = pd.read_parquet(SCORES_PARQUET)
    fits, point = point_estimates(scores)
    boot_iv = {}
    for m in bootstrap.METHODS:
        b = bootstrap.load_replicates(m)
        if len(b):
            boot_iv[m] = bootstrap.intervals(point, b)
    lb = leaderboard(scores, point, boot_iv)
    lb.to_csv(config.REPORTS_DIR / "leaderboard_pilot.csv", index=False)
    sim = simulation.load_results()
    sim_summary, pop = simulation.summarize(sim) if len(sim) else (pd.DataFrame(), pd.DataFrame())
    sim_summary.to_csv(config.REPORTS_DIR / "simulation_summary.csv", index=False)
    cov = coverage_sim.load_results()
    cov_summary = coverage_sim.summarize(cov, pop) if len(cov) else pd.DataFrame()
    cov_summary.to_csv(config.REPORTS_DIR / "coverage_summary.csv", index=False)
    REPORT.write_text(report(lb, variance_table(fits), sim_summary, cov_summary, cov, boot_iv))
    print(f"report in {REPORT}")


def _sim_view(s: pd.DataFrame) -> pd.DataFrame:
    keep = ["dgp", "target_sd_setting", "score", "target", "reps", "target_sd", "sd_catcher_reml", "est_sd", "corr",
            "corr_mcse", "slope", "slope_mcse", "rmse", "flagged", "coverage_model"]
    return s[[c for c in keep if c in s]]


def report(lb, var, sim_summary, cov_summary, cov, boot_iv) -> str:
    out = ["# Phases 2-3 pilot report (revised after review)", "",
           "Generated by `python3.12 -m gamecalling.phase23`. Count-based pilot. Costs are runs per 100 pitches for the "
           "batting team; leaderboard columns are sign-flipped to runs saved vs. average per 100 pitches (higher = "
           "better). Catchers are MLBAM IDs. No 2024-2025 persistence correlation is computed, and no verdict is drawn.",
           "",
           "## Status", "",
           "- **Interval coverage and centering are unvalidated.** The leaderboard's uncertainty is not established. "
           "Any interval below is labeled by its bootstrap method and is not a validated interval.",
           "- Catchers whose intervals exclude 0 are exploratory only.",
           "- The observed catcher SDs are not compared with null-simulation SDs by subtraction or ratio; the null "
           "simulation shows only that D can produce between-catcher spread when none exists.",
           "- Shrinkage (slopes) and model-based coverage in the recovery simulation are diagnostics.",
           "- Recovery and coverage results are conditional on the real payoff estimates.", ""]

    out += ["## Ranking model", "",
            "Exact REML from sufficient statistics, verified against an independent implementation (statsmodels "
            "MixedLM): identical REML log-likelihood at the same parameters, matching variance components, catcher "
            "effects and (against dense formulas) prediction-error variances, including zero catcher variance, weak "
            "connections (an isolated pair; a catcher with one shared pitcher) and the pitcher-fixed-effects model "
            "(`tests/test_phase23.py`). Convergence is checked on every fit (first-order optimality on the box plus a "
            "fresh-start recheck). Numerical correctness does not establish statistical validity for estimated, "
            "dependent pitch scores; the simulations below address that separately.", "",
            "Variance components on the real pilot scores (SDs per 100 pitches):", "", _md(var, "{:.4f}"), ""]

    out += ["## Bootstrap", "",
            "- **Representation:** a game drawn m times is its rows with integer weight m; explicit duplicates and "
            "weights give identical fits through the whole pipeline (tested on a 450-game slice).",
            "- **Methods:** `plain` (reference, unmodified pipeline) and `firstcopy` (experimental: pooling "
            "concentrations and ranking variance components estimated with weight 1 per drawn game). Outputs are "
            "versioned by method; the earlier 200 duplicated-row first-copy replicates are kept as "
            "`data/bootstrap/firstcopy_dup_v1` (diagnostic only).",
            "- **Collapse trace:** `reports/bootstrap_trace.md`. In the plain replicate the pitcher-level outcome "
            "concentration falls from about 110 to about 5 (contact: about 130 to about 9) in every fold, fitted "
            "pitcher cells barely shrink, per-pitch score noise rises about fivefold and the D catcher SD rises to "
            "about 0.10. With identical true cell probabilities the plain replicate still estimates a concentration "
            "of about 3. This is the nonparametric bootstrap's empirical distribution acting as the truth, which "
            "exaggerates between-cell heterogeneity; parametric bootstraps from the fitted prior (Laird and Louis, "
            "1987) are the standard alternative. The first-copy variant keeps concentrations near the original but "
            "changes the estimator inside the replicate (scores are still noisier and the mean of D shifts).", ""]
    if boot_iv:
        out += [f"Real-data bootstrap replicates available for: {', '.join(boot_iv)}.", ""]
    else:
        out += ["No real-data replicates for the revised (weighted, versioned) methods have been run; the leaderboard "
                "shows point estimates only.", ""]

    if len(sim_summary):
        out += ["## Estimator-recovery simulation (v2)", "",
                "Design in `gamecalling/simulation.py`. Catcher effects fixed per setting; every catcher evaluated on "
                "the same predefined opportunities. Targets: `scientific` (policy run value on common PA starts, "
                "exact); `own population` (expected D or A under the catcher's policy on common decision states, "
                "with D's independent selection kept, averaged over replicates = repeated training samples); `own "
                "conditional` (the same, conditional on each replicate's fitted models); `true regret (diagnostic)`. "
                "All centered on the mean over qualifying catchers. Means over replicates with Monte Carlo SEs. "
                "`flagged` and `coverage_model` use the model-based intervals (diagnostics).", "",
                "**Note:** on common opportunities the centered D and A population targets coincide (the "
                "recommendation and baseline terms depend only on the state, so they cancel between catchers); they "
                "differ from the scientific target in scale because the fitted models shrink action differences.", "",
                _md(_sim_view(sim_summary), "{:.4f}"), ""]

    if len(cov_summary):
        n_ds = cov[["dgp", "target_sd_setting", "rep"]].drop_duplicates().shape[0]
        nb = int(cov["n_boot"].iloc[0])
        out += ["## Nested coverage of the bootstrap intervals (first pass)", "",
                f"{n_ds} simulated datasets, {nb} bootstrap replicates per method each (percentile 95% intervals, "
                "centered on the qualifying-catcher mean). Coverage of the target by qualifying catchers' intervals; "
                "`coverage_mcse` treats datasets as the independent unit. `boot_se_over_sd` = mean bootstrap SE / SD "
                "of the point estimates across datasets (1 = calibrated). With this few replicates the percentile "
                "endpoints are themselves noisy; this pass is for detecting gross failures.", "",
                _md(cov_summary, "{:.4f}"), ""]

    for season in sorted(lb["season"].unique()):
        s = lb[lb["season"] == season]
        out += [f"## Leaderboard {season} (catchers with >= {QUALIFY} pitches; point estimates)", "",
                f"Runs saved vs. average per 100 pitches. {len(s)} catchers. Correlation of D (random) with D "
                f"(pitcher fixed effects): {np.corrcoef(s['D_random_saved'], s['D_fixed_saved'])[0, 1]:.3f}; D with A: "
                f"{np.corrcoef(s['D_random_saved'], s['A_random_saved'])[0, 1]:.3f}. Full table in "
                "`reports/leaderboard_pilot.csv`. No tiers are claimed.", ""]
    out += ["## Connection map", "", "See `reports/network_pilot.md` (connected groups, bridges, bridge removal, "
            "figures).", ""]
    return "\n".join(out)


if __name__ == "__main__":
    main()
