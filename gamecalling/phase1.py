"""Phase 1 pilot: fit role models, solve, score every scorable pitch and run the validation checks.

Run with: python3.12 -m gamecalling.phase1   (needs the Phase 0 tables)
Writes data/phase1_scores.parquet and reports/phase1_pilot.md (+ CSVs).
"""

import time

import numpy as np
import pandas as pd

from gamecalling import arsenal, config, scoring, validation

SCORES_PARQUET = config.DATA_DIR / "phase1_scores.parquet"
REPORT = config.REPORTS_DIR / "phase1_pilot.md"


ID_COLUMNS = {"season", "fold", "scoring_fold", "pitcher", "catcher", "base_out", "outs", "bases"}


def _md(df: pd.DataFrame, floatfmt="{:.4f}") -> str:
    cols = list(df.columns)
    lines = ["| " + " | ".join(map(str, cols)) + " |", "|" + "---|" * len(cols)]
    for row in df.itertuples(index=False):
        cells = []
        for col, v in zip(cols, row):
            if col in ID_COLUMNS and isinstance(v, (int, float, np.integer, np.floating)):
                cells.append(str(int(v)))
            elif isinstance(v, (bool, np.bool_)):
                cells.append("yes" if v else "no")
            elif isinstance(v, (int, np.integer)):
                cells.append(f"{v:,}")
            elif isinstance(v, (float, np.floating)):
                cells.append(f"{int(v):,}" if col in ("n", "units") else floatfmt.format(v))
            else:
                cells.append(str(v))
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines)


def main() -> None:
    t0 = time.perf_counter()
    pitches = pd.read_parquet(config.PITCHES_PARQUET)
    pas = pd.read_parquet(config.PAS_PARQUET)
    support = pd.read_parquet(config.DATA_DIR / "arsenal_support.parquet")
    t_load = time.perf_counter() - t0

    t = time.perf_counter()
    run = scoring.run_pilot(pitches, pas, support, keep_solutions=True)
    t_pipeline = time.perf_counter() - t
    scores = run.scores
    scores.to_parquet(SCORES_PARQUET, index=False)

    t = time.perf_counter()
    sims = []
    for season in config.SEASONS:
        sol = run.solutions[season, 0]
        role = run.roles[season, arsenal.fold_roles(0)[1]]
        sims.append(validation.simulation_check(sol["value"], sol["units"], role).assign(season=season))
    sim, z_crit = validation.add_noise_flags(pd.concat(sims, ignore_index=True))
    t_sim = time.perf_counter() - t

    cal = validation.calibration_check(pitches, run.roles)
    cal_contact = validation.calibration_check(pitches, run.roles, kind="contact")
    re288 = validation.re288_check(pitches, pas, run.roles)
    t_total = time.perf_counter() - t0

    config.REPORTS_DIR.mkdir(exist_ok=True)
    sim.to_csv(config.REPORTS_DIR / "phase1_simulation.csv", index=False)
    cal.to_csv(config.REPORTS_DIR / "phase1_calibration.csv", index=False)
    pd.concat([v.assign(table=k) for k, v in re288.items()]).to_csv(config.REPORTS_DIR / "phase1_re288.csv", index=False)
    REPORT.write_text(report(pitches, run, sim, z_crit, cal, cal_contact, re288,
                             dict(load=t_load, pipeline=t_pipeline, simulation=t_sim, total=t_total)))
    print(f"{len(scores):,} pitches scored; report in {REPORT}")


def report(pitches, run, sim, z_crit, cal, cal_contact, re288, times) -> str:
    s = run.scores
    out = ["# Phase 1 pilot report", "",
           "Generated by `python3.12 -m gamecalling.phase1`. Count-based pilot: state = count, batter hand, pitcher; "
           "action = Statcast pitch type; base-out state is the context of each solve. Costs are runs for the batting "
           "team (lower = better for the pitcher); the display convention (runs saved, higher = better) flips the sign "
           "and is applied only in rankings.", ""]

    # Coverage of scoring
    scorable = pitches[pitches["scorable"]].groupby("season").size()
    scored = s.groupby("season").size()
    out += ["## Scored pitches", "",
            _md(pd.DataFrame({"season": scorable.index, "scorable": scorable.values, "scored": scored.values})), ""]

    # Role models
    rows = []
    for (season, fold), r in sorted(run.roles.items()):
        rows.append(dict(season=season, fold=fold,
                         outcome_alpha_league=r.outcome.alpha_league, outcome_alpha_pitcher=r.outcome.alpha_cell,
                         contact_alpha_league=r.contact.alpha_league, contact_alpha_pitcher=r.contact.alpha_cell,
                         payoff_fallback_cells=int(r.payoffs.contact_fallback.sum()),
                         re288_fallback_cells=int(r.re288_fallback.sum())))
    pol = []
    for (season, k), sol in sorted(run.solutions.items()):
        for role_name in ("select", "value"):
            p = sol[role_name].policy
            vc = p.prior_source.value_counts()
            pol.append(dict(season=season, scoring_fold=k, role=role_name, alpha=p.alpha, units=len(p.prior_source),
                            prior_hand=int(vc.get("hand", 0)), prior_both_hands=int(vc.get("both_hands", 0)),
                            prior_uniform=int(vc.get("uniform", 0))))
    out += ["## Role models", "",
            "Empirical-Bayes Dirichlet-multinomial concentrations (pseudo-observations) estimated by marginal "
            "likelihood from each role's own fold. League level: count x hand x pitch type toward count x hand "
            "(contact: hand x pitch type toward hand). Pitcher level: pitcher x pitch type x count x hand toward the "
            "league level (contact: pitcher x pitch type x hand).", "",
            _md(pd.DataFrame(rows), "{:.1f}"), "",
            "Reference policy: pitcher x hand mix by count over the scoring fold's eligible set, pulled toward the "
            "pitcher's mix against that hand in the role's fold. `prior_both_hands` / `prior_uniform` count "
            "pitcher-hand units with no eligible pitches to that hand (or at all) in that fold.", "",
            _md(pd.DataFrame(pol), "{:.1f}"), ""]

    # Criterion 2
    n_sims = 4_000_000
    out += ["## Criterion 2: solver correctness", "",
            "Known-answer cases: `tests/test_phase1.py` (foul loop, certain transitions, balls only, strikes only, "
            "mixed full count, optimal foul loop) all match to 1e-13.", "",
            f"Simulation: V(0-0) of the valuation solve for scoring fold 0, for the 4 highest-volume and 4 random "
            f"pitcher-hand units (>= 50 training pitches) at bases empty/0 out, 1-2-/2 out and loaded/2 out, "
            f"{n_sims:,} simulated at-bats each, contact bins drawn. Tolerance {validation.SIM_TOL} runs; "
            f"Bonferroni |z| bound {z_crit:.2f} over all {len(sim)} checks.", "",
            f"- Within tolerance: {int(sim['within_tol'].sum())} of {len(sim)}. Beyond simulation noise: "
            f"{int(sim['beyond_noise'].sum())}. Largest |difference|: {sim['diff'].abs().max():.5f} runs. "
            f"Largest simulation SE: {sim['se'].max():.5f}.", "",
            _md(sim[["season", "pitcher", "stand", "base_out", "solver", "simulated", "diff", "se", "z", "within_tol"]],
                "{:.5f}"), ""]

    # Criterion 3
    out += ["## Criterion 3: calibration and log loss (held out)", "",
            "Each scoring fold's scorable, fit-eligible pitches, predicted by its valuation role; folds pooled within "
            "season. Calibration error = sample-weighted mean |predicted - observed| over 10 equal-count bins, per "
            f"outcome; threshold {validation.CALIBRATION_MAX}. Baseline = league count x pitch type in the valuation "
            "fold, plus one pseudo-observation at the league count mix; `passes` uses it. "
            "`league_pooled_log_loss` is the matched comparison: the model's own pooled league level (same hand "
            "split and pooling), so log_loss minus it is the gain from pitcher-specific cells alone.", "",
            _md(cal), "",
            "Contact-bin model (diagnostic, not a criterion). Baseline = league pitch type plus one pseudo-observation "
            "at the overall bin mix.", "", _md(cal_contact), ""]

    # Criterion 4
    out += ["## Criterion 4: league-pooled model vs. held-out RE288 (diagnostic)", "",
            "Model: coarser than the scoring pipeline. Pitch types are collapsed into one action per hand with the "
            "valuation fold's league outcome mix by count, and the contact-bin mix is per hand and independent of "
            "count; values use that fold's payoffs. Empirical: runs from each held-out thrown pitch (re24_eligible "
            "PAs) to the end of the half-inning. Gap = model - empirical.", "",
            "- The gaps reflect these simplifications as well as runner events between pitches (not modeled). "
            "Which of them drives a given gap has not been checked.",
            "- `se_fixed_model` is clustered by game and treats the fitted model values as fixed. It leaves out "
            "uncertainty in the estimated probabilities and payoffs and the dependence from shared training folds, "
            "so it understates the gap's uncertainty. Whole-pipeline resampling is needed for that.", ""]
    for name in ("overall", "by_season", "by_outs", "by_bases", "by_count"):
        out += [f"**{name.replace('_', ' ')}**", "", _md(re288[name]), ""]

    # Scores
    cols = ["D", "A", "B", "D_opt", "D_1p"]
    summ = s.groupby("season")[cols].mean().mul(100).reset_index()
    out += ["## Scores (internal cost, runs per 100 pitches, before any ranking model)", "",
            "D = main scored difference; A = advantage vs. pooled reference (addendum); B = D - A; D_opt = optimal "
            "continuation; D_1p = one-pitch RE288 benchmark. Pitch-level means only; no catcher results are "
            "reported in Phase 1.", "", _md(summ), ""]
    dist = s[cols].describe(percentiles=[0.05, 0.25, 0.5, 0.75, 0.95]).T.drop(columns="count").reset_index().rename(columns={"index": "score"})
    out += ["Per-pitch distribution (runs per pitch):", "", _md(dist, "{:.4f}"), ""]
    corr = s[cols].corr().reset_index().rename(columns={"index": "score"})
    out += ["Per-pitch correlations:", "", _md(corr, "{:.3f}"), ""]
    agree = pd.DataFrame({
        "measure": ["actual = recommended (D)", "actual = recommended (optimal)", "actual = recommended (one-pitch)",
                    "D < 0", "mean eligible pitch types"],
        "value": [s["agree"].mean(), s["agree_opt"].mean(), s["agree_1p"].mean(), (s["D"] < 0).mean(),
                  s["n_eligible"].mean()]})
    out += [_md(agree, "{:.3f}"), ""]

    # Criterion 8
    tm = run.timings
    out += ["## Criterion 8: computation (pending)", "",
            "Not yet met. The plan requires a measured benchmark of one fit, one batch of solves and a 10-replicate "
            "resampling run. Only fitting, solving and scoring are timed here; resampling and the ranking model are "
            "not built yet.", "",
            f"- Load tables: {times['load']:.1f} s. Full pipeline (12 role fits, 12 solves, 6 scoring folds): "
            f"{times['pipeline']:.1f} s.",
            f"- One role fit: {np.mean(tm['fit_role']):.2f} s. One role solve (reference + optimal + one-pitch, all "
            f"pitcher-hands x 24 base-out states): {np.mean(tm['solve_role']):.2f} s.",
            f"- Simulation check: {times['simulation']:.1f} s. Whole run: {times['total']:.1f} s.",
            f"- Initial extrapolation, not a measurement: if a bootstrap replicate costs about one pipeline run "
            f"({times['pipeline']:.0f} s), 10 replicates would take about {10 * times['pipeline'] / 60:.0f} min "
            f"before the ranking-model fits. To be replaced by the measured 10-replicate run. The batter-index model "
            "(per-PA solves) will cost more.", ""]
    return "\n".join(out)


if __name__ == "__main__":
    main()
